      SUBROUTINE EVAL_DA(DA_IDX, POINT, RES)
*     **************************************
*     Evaluates DA variable at a point
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER DA_IDX
      DOUBLE PRECISION POINT(*)
      DOUBLE PRECISION RES
      
      PARAMETER(LMEM=2000000,LVAR=100000,LDIM=1000)
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON /DAFOXINT/ NTYP,NBEG,NEND,NMAX, NC, NDIM,IDIM, IVAR,IMEM
      COMMON /DAFOXDBL/ CC
      COMMON /FOXTYID/ NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
      
      INTEGER IE1(LEA),IE2(LEA),IEO(LEA),IA1(0:LIA),IA2(0:LIA),
     *        NCFLT(LEA),IEW(LNV),IED(LNV),LEW,LEWI,IESP,
     *        NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT,ITM,LENTM,ITMPR
      DOUBLE PRECISION CDA(2*LEA),EPS,EPSMAC,TMT,TMS,EPSM,TOLTMR
      COMMON /DACOM/ CDA,EPS,EPSMAC,IE1,IE2,IEO,IA1,IA2,NCFLT,
     *       IEW,IED,LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      
      INTEGER JJ(LNV)
      INTEGER I, K, NM, I1, I2, EXP
      DOUBLE PRECISION TERM, PVAL
      
      RES = 0.0D0
      
      DO 100 I = NBEG(DA_IDX), NEND(DA_IDX)
         NM = NC(I)
*        Decode NM to Exponents JJ
         CALL DAENC(IE1(NM), IE2(NM), JJ)
         
         TERM = CC(I)
         
*        Multiply by variables
         DO 50 K=1,NVMAX
             EXP = JJ(K)
             IF (EXP .GT. 0) THEN
                 TERM = TERM * (POINT(K) ** EXP)
             ENDIF
 50      CONTINUE
         
         RES = RES + TERM
 100  CONTINUE
      
      RETURN
      END

