
      SUBROUTINE SETUP_COSY(KORDER, KVAR, KMAXMEM)
*     ********************************************
*     Wrapper to initialize COSY from scalar integers
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
*
*-----MEMORY MANAGEMENT -----------------------------------------------------
      PARAMETER(LMEM=2000000,LVAR=100000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON /DAFOXINT/ NTYP,NBEG,NEND,NMAX, NC, NDIM,IDIM, IVAR,IMEM
      COMMON /DAFOXDBL/ CC
      COMMON /FOXTYID/ NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
*----------------------------------------------------------------------------
      INTEGER KORDER, KVAR, KMAXMEM
      INTEGER INO, INV, IIU, INM
      INTEGER IC(1)
*
*     Allocate and set Order object
      CALL FOXALL(IC, 1, 1)
      INO = IC(1)
      CC(NBEG(INO)) = DBLE(KORDER)
*
*     Allocate and set Dimension object
      CALL FOXALL(IC, 1, 1)
      INV = IC(1)
      CC(NBEG(INV)) = DBLE(KVAR)
*
*     Allocate and set Unit object
      CALL FOXALL(IC, 1, 1)
      IIU = IC(1)
      CC(NBEG(IIU)) = 6.0D0
*
*     Allocate Output Max Memory object
      CALL FOXALL(IC, 1, 1)
      INM = IC(1)
*
*     Call original DAINI
      CALL DAINI(INO, INV, IIU, INM)
*
*     Return actual Max Monomials
      KMAXMEM = NINT(CC(NBEG(INM)))
*
      RETURN
      END

