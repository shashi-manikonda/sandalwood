     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT
      I = NBEG(IDX) + (ITERM - 1) * 2
      IF (I .GT. NEND(IDX)) THEN
          RE_VAL = 0.0D0
          IM_VAL = 0.0D0
          RETURN
      ENDIF
      RE_VAL = CC(I)
      IM_VAL = CC(I+1)
      NM = NC(I)
      CALL DAENC(IE1(NM), IE2(NM), JJ)
      DO 10 K = 1, NVMAX
          EXPS(K) = JJ(K)
 10   CONTINUE
      RETURN
      END

