      SUBROUTINE EVAL_DA(IDX, POINTS, VAL)
     *  BIND(C, NAME='eval_da')
      USE ISO_C_BINDING
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) IDX
      DOUBLE PRECISION POINTS(*), VAL
      INTEGER I, K, NM, JJ(40)
      DOUBLE PRECISION TERM, COEFF
      PARAMETER(LMEM=140000000,LVAR=10000000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON NTYP, NBEG, NEND, NMAX, CC, NC, NDIM, IDIM, IVAR, IMEM
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
     *       IEO(LEA),IA1(0:LIA),IA2(0:LIA),NCFLT(LEA),
     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT
      
      VAL = 0.0D0
      IF (NEND(IDX) .LT. NBEG(IDX)) RETURN
      
      DO 100 I = NBEG(IDX), NEND(IDX)
         COEFF = CC(I)
         IF (ABS(COEFF) .GT. 0.0D0) THEN
             NM = NC(I)
             IF (NM .EQ. 0) THEN
                 TERM = 1.0D0
             ELSE
                 CALL DAENC(IE1(NM), IE2(NM), JJ)
                 TERM = 1.0D0
                 DO 50 K = 1, NVMAX
                     IF (JJ(K) .GT. 0) THEN
                         TERM = TERM * (POINTS(K)**JJ(K))
                     ENDIF
 50              CONTINUE
             ENDIF
             VAL = VAL + COEFF * TERM
         ENDIF
 100  CONTINUE
      RETURN
      END

      SUBROUTINE COSY_SET_COEFFS(IDX, VALS, EXPS, N)
     *  BIND(C, NAME='cosy_set_coeffs')
      USE ISO_C_BINDING
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) IDX, N, EXPS(*), I, J, NM, K
      DOUBLE PRECISION VALS(N)
      PARAMETER(LMEM=140000000,LVAR=10000000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON NTYP, NBEG, NEND, NMAX, CC, NC, NDIM, IDIM, IVAR, IMEM
      INTEGER NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
      COMMON /TYID/ NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      INTEGER IE1(LEA),IE2(LEA),IEO(LEA),IA1(0:LIA),IA2(0:LIA),
     *        NCFLT(LEA),IEW(LNV),IED(LNV),LEW,LEWI,IESP,
     *        NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1,IE2,IEO,IA1,IA2,NCFLT,
     *       IEW,IED,LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      INTEGER JJ(LNV)
      
      CALL DACON(IDX, 0.0D0)
      
      ! Ensure NTYP is set using GLOBAL NDA
      DO 100 I = 1, N
          DO 10 K = 1, NVMAX
              JJ(K) = EXPS((I-1)*NVMAX + K)
 10       CONTINUE
          CALL DAENE(JJ, NM)
          IF (NM .GT. 0) THEN
             J = NBEG(IDX) + I - 1
             IF (J .LE. NMAX(IDX)) THEN
                CC(J) = VALS(I)
                NC(J) = NM
                NEND(IDX) = MAX(NEND(IDX), J)
             ENDIF
          ENDIF
 100  CONTINUE
      NTYP(IDX) = NDA
      RETURN
      END

      SUBROUTINE COSY_SET_CD_COEFFS(IDX, RE_VALS, IM_VALS, EXPS, N)
     *  BIND(C, NAME='cosy_set_cd_coeffs')
      USE ISO_C_BINDING
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) IDX, N, EXPS(*), I, J, NM, K
      DOUBLE PRECISION RE_VALS(N), IM_VALS(N)
      PARAMETER(LMEM=140000000,LVAR=10000000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON NTYP, NBEG, NEND, NMAX, CC, NC, NDIM, IDIM, IVAR, IMEM
      INTEGER NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
      COMMON /TYID/ NRE,NST,NLO,NCM,NVE,NDA,NCD,NGR
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      INTEGER IE1(LEA),IE2(LEA),IEO(LEA),IA1(0:LIA),IA2(0:LIA),
     *        NCFLT(LEA),IEW(LNV),IED(LNV),LEW,LEWI,IESP,
     *        NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1,IE2,IEO,IA1,IA2,NCFLT,
     *       IEW,IED,LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      INTEGER JJ(LNV)
      INTEGER IC(2)
      
      ! Initialize to zero (Complex)
      CALL FOXALL(IC, 2, NMMAX)
      NTYP(IC(1)) = NRE
      NTYP(IC(2)) = NRE
      CALL DACON(IC(1), 0.0D0)
      CALL DACON(IC(2), 0.0D0)
      CALL SET_CD_PARTS(IDX, IC(1), IC(2))
      CALL FOXDAL(IC, 2)
      
      DO 200 I = 1, N
          DO 20 K = 1, NVMAX
              JJ(K) = EXPS((I-1)*NVMAX + K)
  20      CONTINUE
          CALL DAENE(JJ, NM)
          IF (NM .GT. 0) THEN
             J = NBEG(IDX) + (I - 1) * 2
             IF ((J+1) .LE. NMAX(IDX)) THEN
                CC(J)   = RE_VALS(I)
                CC(J+1) = IM_VALS(I)
                NC(J)   = NM
                NC(J+1) = NM
                NEND(IDX) = MAX(NEND(IDX), J+1)
             ENDIF
          ENDIF
  200  CONTINUE
      NTYP(IDX) = NCD
      RETURN
      END

      SUBROUTINE GET_DA_COEFF_BY_INDEX(IDX, ITERM, EXPS, VAL)
     *  BIND(C, NAME='get_da_coeff_by_index')
      USE ISO_C_BINDING
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) IDX, ITERM, EXPS(*), I, K, NM, JJ(40)
      DOUBLE PRECISION VAL
      PARAMETER(LMEM=140000000,LVAR=10000000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON NTYP, NBEG, NEND, NMAX, CC, NC, NDIM, IDIM, IVAR, IMEM
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
     *       IEO(LEA),IA1(0:LIA),IA2(0:LIA),NCFLT(LEA),
     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT
      I = NBEG(IDX) + ITERM - 1
      IF (I .GT. NEND(IDX)) THEN
          VAL = 0.0D0
          RETURN
      ENDIF
      VAL = CC(I)
      NM = NC(I)
      IF (NM .GT. 0) THEN
         CALL DAENC(IE1(NM), IE2(NM), JJ)
         DO 10 K = 1, NVMAX
             EXPS(K) = JJ(K)
 10      CONTINUE
      ELSE
         DO 11 K = 1, NVMAX
             EXPS(K) = 0
 11      CONTINUE
      ENDIF
      RETURN
      END
      SUBROUTINE GET_CDA_COEFF_BY_INDEX(IDX, ITERM, EXPS, RE_VAL, 
     *  IM_VAL) BIND(C, NAME='get_cda_coeff_by_index')
      USE ISO_C_BINDING
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) IDX, ITERM, EXPS(*)
      DOUBLE PRECISION RE_VAL, IM_VAL
      INTEGER I, K, NM, JJ(40)
      PARAMETER(LMEM=140000000,LVAR=10000000,LDIM=1000)
      INTEGER NTYP(LVAR),NBEG(LVAR),NEND(LVAR),NMAX(LVAR),
     *        NC(LMEM),NDIM(LDIM)
      DOUBLE PRECISION CC(LMEM)
      COMMON NTYP, NBEG, NEND, NMAX, CC, NC, NDIM, IDIM, IVAR, IMEM
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
