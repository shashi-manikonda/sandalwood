      INTEGER(C_INT) N, NMX, IER
      DOUBLE PRECISION A(N*N), AI(N*N)
      DOUBLE PRECISION AMAT(50, 50), AIMAT(50, 50)
      INTEGER I, J

      NMX = 50
      IF (N .GT. 50) THEN
         PRINT *, 'MATRIX TOO LARGE FOR MATINV (MAX 50)'
         RETURN
      ENDIF

*     Unflatten A -> AMAT
      DO I=1,N
         DO J=1,N
            AMAT(I,J) = A((I-1)*N + J)
         ENDDO
      ENDDO

      CALL MATINV(AMAT, AIMAT, N, NMX, IER)

*     Flatten AIMAT -> AI
      DO I=1,N
         DO J=1,N
            AI((I-1)*N + J) = AIMAT(I,J)
         ENDDO
      ENDDO
      
      RETURN
      END


