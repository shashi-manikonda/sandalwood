      SUBROUTINE COMPUTE_DA_PEP(INA, N, INC)
     *  BIND(C, NAME='compute_da_pep')
      USE ISO_C_BINDING
C     Integer Power: C = A^N
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) INA, N, INC
      INTEGER IC(100)
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
     *       IEO(LEA),IA1(0:LIA),IA2(0:LIA),NCFLT(LEA),
     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT
      CALL FOXALL(IC, 1, NMMAX)
      INC = IC(1)
C     Init INC = 1.0 (Constant DA)
      CALL DACON(INC, 1.0D0)

      IF(N.EQ.0) RETURN

      IF(N.GT.0) THEN
         ! Simple loop multiplication: INC = INC * INA
         DO I=1, N
            ! Perform INC = INC * INA
            ! Need temp for result because DAMDA(A, B, C) stores in C
            ! Can C be A? "IF((INA.EQ.INC).OR.(INB.EQ.INC)) CALL DANFI" -> Error!
            ! So need temp.
            CALL FOXALL(IC, 1, NMMAX)
            I_TMP = IC(1)
            CALL DAMDA(INC, INA, I_TMP)
            ! Copy back TMP to INC
            CALL DACOP(I_TMP, INC)
            ! Free TMP
            IC(1) = I_TMP
            CALL FOXDAL(IC, 1)
         END DO
      ELSE
         ! N < 0: Compute A^|N| then Invert
         ! INC is already 1.0 so we can accumulate positive power first
         DO I=1, ABS(N)
            CALL FOXALL(IC, 1, NMMAX)
            I_TMP = IC(1)
            CALL DAMDA(INC, INA, I_TMP)
            CALL DACOP(I_TMP, INC)
            IC(1) = I_TMP
            CALL FOXDAL(IC, 1)
         END DO
         ! Now Invert INC -> INC = 1/INC
         CALL FOXALL(IC, 1, NMMAX)
         I_TMP = IC(1)
         CALL DAMUI(INC, I_TMP) ! I_TMP = 1/INC
         CALL DACOP(I_TMP, INC) ! INC = I_TMP
         IC(1) = I_TMP
         CALL FOXDAL(IC, 1)
      END IF
      RETURN
      END

      SUBROUTINE COMPUTE_DA_PKP(INA, REXP, INC)
     *  BIND(C, NAME='compute_da_pkp')
      USE ISO_C_BINDING
*     *****************************************
*     Robust power using DAFUN: INC = INA**REXP
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) INA, INC
      DOUBLE PRECISION REXP
      INTEGER IC(1)
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      INTEGER IE1(LEA),IE2(LEA),IEO(LEA),IA1(0:LIA),IA2(0:LIA),
     *        NCFLT(LEA),IEW(LNV),IED(LNV),LEW,LEWI,IESP,
     *        NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      DOUBLE PRECISION CDA(2*LEA),EPS,EPSMAC
      COMMON /DACOM/ CDA,EPS,EPSMAC,IE1,IE2,IEO,IA1,IA2,NCFLT,
     *       IEW,IED,LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,LFLT,NFLT
      DIMENSION XF(0:LNO)
      DOUBLE PRECISION RE

      A0 = RE(INA)
      CNORM = A0
      
      IF (A0 .EQ. 0.0D0) THEN
         ! Handle zero base for non-negative integer powers
         IPOW = NINT(REXP)
         IF (ABS(REXP - DBLE(IPOW)) .LT. 1.0D-10 .AND. IPOW .GE. 0) THEN
            DO I=0, NOCUT
               XF(I) = 0.0D0
            ENDDO
            IF (IPOW .LE. NOCUT) XF(IPOW) = 1.0D0
            CNORM = 1.0D0
         ELSE
            PRINT*, '$$$ ERROR IN COMPUTE_DA_PKP, BASE IS ZERO'
            CALL FOXDEB
         ENDIF
      ELSE
         XF(0) = A0**REXP
         DO 10 I=1,NOCUT
            XF(I) = XF(I-1) * (REXP - DBLE(I) + 1.0D0) / DBLE(I)
  10     CONTINUE
      ENDIF

      IF (NMMAX .LE. 0) THEN
         CALL FOXALL(IC, 1, 50000)
      ELSE
         CALL FOXALL(IC, 1, NMMAX)
      ENDIF
      INC = IC(1)
      CALL DAFUN(INA, CNORM, XF, NOCUT, INC)
      
      RETURN
      END

      SUBROUTINE COMPUTE_DA_ATAN2(INY, INX, INC)
     *  BIND(C, NAME='compute_da_atan2')
      USE ISO_C_BINDING
C     Computes atan2(Y, X) using DAATAN and quadrant logic
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) INY, INX, INC
      INTEGER IC(100), I_EXPS(40)
      DOUBLE PRECISION X0, Y0, PI, PI_2
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
     *       IEO(LEA),IA1(0:LIA),IA2(0:LIA),NCFLT(LEA),
     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT
      INTERFACE
        SUBROUTINE GET_DA_COEFF_BY_INDEX(IDX, ITERM, EXPS, VAL)
     *    BIND(C, NAME='get_da_coeff_by_index')
          USE ISO_C_BINDING
          INTEGER(C_INT) IDX, ITERM, EXPS(*)
          DOUBLE PRECISION VAL
        END SUBROUTINE
      END INTERFACE
      
      PI = 3.14159265358979323846D0
      PI_2 = 1.57079632679489661923D0

C     Allocate Temps
      CALL FOXALL(IC, 5, NMMAX)
      I_TMP = IC(1)
      I_QUOT = IC(2)
      
C     Get Constant Parts X0, Y0 (Term index 1 is constant in COSY)
      CALL GET_DA_COEFF_BY_INDEX(INX, 1, I_EXPS, X0)
      CALL GET_DA_COEFF_BY_INDEX(INY, 1, I_EXPS, Y0)
      
      IF (X0.GT.0.D0) THEN
         CALL DADDA(INY, INX, I_QUOT)
         CALL DAATAN(I_QUOT, INC)
      ELSE IF (X0.LT.0.D0) THEN
         IF (Y0.GE.0.D0) THEN
            CALL DADDA(INY, INX, I_QUOT)
            CALL DAATAN(I_QUOT, I_TMP)
            CALL DACON(IC(3), PI)
            CALL DAADA(I_TMP, IC(3), INC)
         ELSE
            CALL DADDA(INY, INX, I_QUOT)
            CALL DAATAN(I_QUOT, I_TMP)
            CALL DACON(IC(3), PI)
            CALL DASDA(I_TMP, IC(3), INC)
         END IF
      ELSE
         IF (Y0.GT.0.D0) THEN
             CALL DACON(INC, PI_2)
         ELSE IF (Y0.LT.0.D0) THEN
             CALL DACON(INC, -PI_2)
         ELSE
             ! Error 0,0, return 0
             CALL DACON(INC, 0.D0)
         END IF
      END IF
      
      CALL FOXDAL(IC, 5)
      RETURN
      END

      SUBROUTINE COMPUTE_CD_LOG(INA, INC)
     *  BIND(C, NAME='compute_cd_log')
      USE ISO_C_BINDING
C     Complex Log: log(A) = log|A| + i*arg(A)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INTEGER(C_INT) INA, INC
      INTEGER I_RE, I_IM, I_RE2, I_IM2, I_R2, I_R, I_LR, I_THETA
      INTEGER I_CD_LR, I_CD_THETA, I_UNIT, I_IM_PART, I_TMP
      INTEGER IC(100), IC_RES(1)
      PARAMETER(LEA=100000,LIA=1400000,LNO=99,LNV=40)
      COMMON /DACOM/ CDA(2*LEA),EPS,EPSMAC,IE1(LEA),IE2(LEA),
     *       IEO(LEA),IA1(0:LIA),IA2(0:LIA),NCFLT(LEA),
     *       IEW(LNV),IED(LNV),LEW,LEWI,IESP,NOMAX,NVMAX,NMMAX,NOCUT,
     *       LFLT,NFLT

      INTERFACE
        SUBROUTINE COMPUTE_DA_ATAN2(Y, X, RES) 
     *    BIND(C, NAME='compute_da_atan2')
          USE ISO_C_BINDING
          INTEGER(C_INT) Y, X, RES
        END SUBROUTINE
      END INTERFACE
      
      ! Alloc Result
      CALL FOXALL(IC_RES, 1, 2*NMMAX)
      INC = IC_RES(1)

      ! Alloc DA Temps (1-8)
      CALL FOXALL(IC, 8, NMMAX)
      I_RE = IC(1)
      I_IM = IC(2)
      I_RE2 = IC(3)
      I_IM2 = IC(4)
      I_R2  = IC(5)
      I_R   = IC(6)
      I_LR  = IC(7)
      I_THETA = IC(8)

      ! Alloc CD Temps (9-13)
      CALL FOXALL(IC(9), 5, 2*NMMAX)
      I_CD_LR    = IC(9)
      I_CD_THETA = IC(10)
      I_UNIT     = IC(11)
      I_IM_PART  = IC(12)
      I_TMP      = IC(13)

      CALL CDRE(INA, I_RE)
      CALL CDIM(INA, I_IM)

      ! log|A| = 0.5 * log(RE^2 + IM^2)
      CALL DASQR(I_RE, I_RE2)
      CALL DASQR(I_IM, I_IM2)
      CALL DAADA(I_RE2, I_IM2, I_R2)
      CALL DASQRT(I_R2, I_R)
      CALL DALOG(I_R, I_LR)

      ! arg(A) = atan2(IM, RE)
      CALL COMPUTE_DA_ATAN2(I_IM, I_RE, I_THETA)

      ! Result = L_R + i * THETA
      CALL CDCMPL(I_LR, I_CD_LR)
      CALL CDCMPL(I_THETA, I_CD_THETA)
      CALL CREATE_CDA_CONST(I_UNIT, 0.D0, 1.D0)
      CALL CDMCD(I_UNIT, I_CD_THETA, I_IM_PART)
      CALL CDACD(I_CD_LR, I_IM_PART, INC)

      ! Cleanup
      CALL FOXDAL(IC, 8)
      CALL FOXDAL(IC(9), 5)
      RETURN
      END

      SUBROUTINE COMPUTE_CD_EXP(INA, INC)
